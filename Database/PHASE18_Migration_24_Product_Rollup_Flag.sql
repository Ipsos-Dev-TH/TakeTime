-- PHASE 18 Migration 24: ตั้งค่ารายสินค้า — รวมใน "ใบสรุปรายได้รายวัน" หรือไม่
-- ════════════════════════════════════════════════════════════════════════════
-- เพิ่มสวิตช์ต่อสินค้า Product.Include_In_Daily_Rollup:
--   1 (ค่าเริ่มต้น) = รวมในใบสรุปรายวันตามปกติ — พฤติกรรมเดิมทุกประการ
--   0               = ไม่รวม: การขายสินค้านั้นจะ "ไม่ถูกลงรายได้/ต้นทุน" ใน
--                     • ใบรับเงินสดสรุปรายวันของขายหน้าร้าน (POS rollup)
--                     • ใบสรุปรายวันของรูมเซอร์วิส
--                     (แถว Product_Out ถูก mark 'EXCLUDED-...' กันวนซ้ำ — ตรวจย้อนหลังได้)
--
-- ตัวอย่างการใช้: "หมูกระทะ" ที่ตกลงกับผู้ทำบัญชีว่าให้ลงรายได้รวมกับค่าห้อง
-- (ชาร์จเข้าห้อง → ไปกับใบเสร็จเช็คเอาท์อยู่แล้ว) — ปิดสวิตช์เพื่อไม่ให้การขายสด
-- หน้าร้านของรายการนี้เข้าใบสรุปรายวันซ้ำอีกทาง
--
-- สิ่งที่ "ไม่กระทบ" (ตั้งใจ):
--   • ขายที่ออกใบกำกับในระบบ (ติ๊ก "ออกใบกำกับภาษี") — ยังออกใบจริงรายใบเหมือนเดิม
--   • ชาร์จเข้าห้อง (Reservation_Product_Charges) — รายได้ยังไปกับใบเสร็จเช็คเอาท์
--   • การตัดสต๊อกจำนวน (qty) — ยังตัดปกติ สวิตช์นี้คุมเฉพาะ "การลงบัญชีในใบสรุปรายวัน"
--
-- idempotent — รันซ้ำได้
-- ════════════════════════════════════════════════════════════════════════════
SET NOCOUNT ON;

IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.Product') AND name = 'Include_In_Daily_Rollup')
BEGIN
    ALTER TABLE dbo.Product
        ADD Include_In_Daily_Rollup BIT NOT NULL
            CONSTRAINT DF_Product_DailyRollup DEFAULT (1);
    PRINT 'Added Product.Include_In_Daily_Rollup (default 1 = รวมเหมือนเดิม)';
END
ELSE
    PRINT 'Product.Include_In_Daily_Rollup already exists - skipped';
GO

PRINT 'PHASE18_24 completed';
GO
